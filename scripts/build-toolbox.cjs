const fs=require('node:fs'),path=require('node:path');
const ts=require('typescript');
const root=path.resolve(__dirname,'..');
const layout=require('../audit/site-layout.json');
const tooltips=require('../audit/site-tooltips.json');
const {compileProgram}=require('../tests/compiler-host.cjs');
const colors={sprites:'#4B7BEC',game:'#8854D0',scene:'#4b6584',animation:'#2C3A47',controller:'#D54322',music:'#f368e0'};

async function main(){
 // Read the original API with no previous metadata layer.
 const {result,options}=await compileProgram('let ready=true',{files:{},omitToolbox:true});
 if(!result.success)throw Error(JSON.stringify(result.diagnostics));
 const api=pxtc.getApiInfo(result.ast,options.jres);
 const blocks=pxtc.getBlocksInfo(api).blocks;
 const entries=[],expected=[],combined=[];
 for(const block of blocks){
  const pack=layout.find(p=>p.id===block.pkg);
  if(!pack||pack.id==='pxt-raycasting')continue;
  if(![1,3].includes(block.kind))continue;
  const group=pack.group||block.attributes.group;
  const category=pack.category||block.attributes.blockNamespace||block.namespace.split('.')[0];
  const hide=block.attributes.blockHidden||block.attributes.deprecated||
   (pack.id==='arcade-timers'&&block.name==='background')||
   (pack.expose&&!pack.expose.includes(block.name))||pack.hide?.includes(block.name);
  const words=block.attributes.block.replace(/\|\|/g,'. Optional: ').replace(/\$?(\w+)=\w+/g,'$1').replace(/\$(\w+)(?:\([^)]*\))?/g,'$1').replace(/[|%]/g,' ').replace(/\s+/g,' ').trim();
  const tip=tooltips[pack.id]?.[block.qName]||tooltips[pack.id]?.[block.name]||block.attributes.jsDoc||words[0].toUpperCase()+words.slice(1)+'.';
  const attrs=[`blockId=${block.attributes.blockId}`,`block=${JSON.stringify(block.attributes.block)}`,`blockNamespace=${category}`,colors[pack.category]?`color="${colors[pack.category]}"`:'',group?`group="${group}"`:'',hide?'blockHidden=true':''].filter(Boolean).join(' ');
  const params=(block.parameters||[]).map(p=>`${p.name}${p.initializer!==undefined?'?':''}: ${p.type}`).join(', ');
  const metadata=`/** ${tip.replace(/\*\//g,'').replace(/\r?\n/g,' ')} */\n//% ${attrs}\n`;
  const ambientNote='// @ts-ignore TS2384: metadata-only overload; implementation remains in the pinned upstream package.\n';
  let declaration;
  if(block.kind===3){
   declaration=metadata+ambientNote+`export function ${block.name}(${params}): ${block.retType};`;
   declaration=wrapNamespace(block.namespace,declaration);
  }else{
   const parts=block.namespace.split('.'),name=parts.pop();
   declaration=`interface ${name} {\n${metadata}${block.name}(${params}): ${block.retType};\n}`;
   if(parts.length)declaration=wrapNamespace(parts.join('.'),declaration);
  }
  entries.push(declaration);expected.push({qName:block.qName,id:block.attributes.blockId,category,group,hidden:!!hide});
 }
 // Combined property blocks inherit placement from their owning class symbol.
 const owners=new Set();
 for(const symbol of Object.values(api.byQName)){
  const pack=layout.find(p=>p.id===symbol.pkg);
  if(symbol.kind!==2||!symbol.attributes.blockCombine||!pack?.category||owners.has(symbol.namespace))continue;
  owners.add(symbol.namespace);
  const parts=symbol.namespace.split('.'),name=parts.pop();
  const meta=`//% blockNamespace=${pack.category} color="${colors[pack.category]}"\nnamespace ${name} { }`;
  entries.push(parts.length?wrapNamespace(parts.join('.'),meta):`//% blockNamespace=${pack.category} color="${colors[pack.category]}"\ndeclare namespace ${name} { }`);
  combined.push({owner:symbol.namespace,category:pack.category});
 }
 // Namespace labels merge without replacing any library implementation.
 entries.push('//% block="Menus"\ndeclare namespace miniMenu { }','//% block="Objects"\ndeclare namespace blockObject { }');
 const source='// Generated by npm run build:toolbox from pinned APIs and the standalone site layout.\n'+
  '// Ambient declarations supply toolbox metadata only; never add implementations here.\n\n'+entries.join('\n\n')+'\n';
 // Check syntax using the ordinary TypeScript parser before the real PXT check.
 const parsed=ts.createSourceFile('toolbox.d.ts',source,ts.ScriptTarget.Latest,true);
 if(parsed.parseDiagnostics.length)throw Error('Invalid generated declaration syntax');
 fs.writeFileSync(path.join(root,'toolbox.d.ts'),source);
 fs.writeFileSync(path.join(root,'audit/toolbox-layout.json'),JSON.stringify(expected,null,2)+'\n');
 fs.writeFileSync(path.join(root,'audit/combined-layout.json'),JSON.stringify(combined,null,2)+'\n');
 console.log(`Generated metadata for ${expected.length} upstream blocks.`);
}
function wrapNamespace(name,body){return `declare namespace ${name} {\n${body}\n}`;}
main().catch(error=>{console.error(error.message);process.exitCode=1});
